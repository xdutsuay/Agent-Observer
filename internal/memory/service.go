package memory

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"time"

	"agent-memory-mcp/internal/app"
	"agent-memory-mcp/internal/core"
	"agent-memory-mcp/internal/patterns"
	"agent-memory-mcp/internal/projects"
	"agent-memory-mcp/internal/smartctx"
	"agent-memory-mcp/internal/store/sqlite"
)

type Service struct {
	store      *sqlite.Store
	detector   *patterns.Detector
	correlator *patterns.Correlator
	packer     *smartctx.Packer
}

func NewService(store *sqlite.Store) app.MemoryService {
	return &Service{
		store:      store,
		detector:   patterns.NewDetector(store),
		correlator: patterns.NewCorrelator(store),
		packer:     smartctx.NewPacker(store),
	}
}

func (s *Service) ResolveRepo(path string) (string, error) {
	rootPath, err := projects.FindProjectRoot(path)
	if err != nil {
		rootPath = path
	}
	repoID := filepath.Base(rootPath)
	if repoID == "." || repoID == "" {
		repoID = "default"
	}

	err = s.store.UpsertRepo(context.Background(), repoID, rootPath)
	return repoID, err
}

func (s *Service) Remember(repoID, kind, content, source string, metadata map[string]any) (string, bool, error) {
	return s.store.InsertMemory(context.Background(), repoID, kind, content, source, metadata, false)
}

func (s *Service) Search(ctx context.Context, query string, repoID *string, kinds []string, limit int) ([]core.Memory, error) {
	return s.store.Search(ctx, query, repoID, kinds, limit)
}

func (s *Service) ListMemories(ctx context.Context, repoID *string, kind *string, limit int) ([]core.Memory, error) {
	return s.store.ListMemories(ctx, repoID, kind, limit)
}

func (s *Service) ListRepos(ctx context.Context) ([]core.RepoListing, error) {
	repos, err := s.store.ListReposDB(ctx)
	if err != nil {
		return nil, err
	}
	res := []core.RepoListing{}
	for _, r := range repos {
		errCount := s.store.FailureErrorCount(ctx, r.ID)
		health := "HEALTHY"
		if errCount > 0 {
			health = "CRITICAL"
		}
		res = append(res, core.RepoListing{
			ID:         r.ID,
			Path:       r.Path,
			Health:     health,
			ErrorCount: errCount,
		})
	}
	return res, nil
}

func (s *Service) GetRepoContext(ctx context.Context, repoID string) (core.RepoContext, error) {
	return s.store.GetRepoContext(ctx, repoID)
}

func (s *Service) MarkFailureResolved(ctx context.Context, repoID, signature string) (bool, error) {
	return s.store.MarkFailureResolved(ctx, repoID, signature)
}

func (s *Service) Forget(ctx context.Context, memoryID, signature, repoID string) (int, error) {
	return s.store.Forget(ctx, memoryID, signature, repoID)
}

func (s *Service) RefreshRelevance(ctx context.Context, repoID *string) (int, int, error) {
	noiseCount, err := s.store.ClassifyNoise(ctx, 7)
	if err != nil {
		return 0, 0, err
	}
	relCount, err := s.store.RefreshRelevance(ctx, repoID)
	return relCount, noiseCount, err
}

func (s *Service) GenerateContextFile(ctx context.Context, repoID string, projectPath string) error {
	path, err := s.BuildContextFile(ctx, repoID, projectPath)
	_ = path
	return err
}

func (s *Service) BuildContextFile(ctx context.Context, repoID string, projectPath string) (string, error) {
	rc, err := s.GetRepoContext(ctx, repoID)
	if err != nil {
		return "", err
	}

	now := time.Now().UTC().Format(time.RFC3339)
	content := fmt.Sprintf("# Agent Memory Context (auto-generated)\n# Project: %s\n# Last updated: %s\n# Do not edit — regenerated by agent-memory-mcp\n\n", repoID, now)

	if rc.Decisions != "(none)" && rc.Decisions != "" {
		content += "## Key Decisions\n" + rc.Decisions + "\n\n"
	}
	if rc.Failures != "(none)" && rc.Failures != "" {
		content += "## Known Issues\n" + rc.Failures + "\n\n"
	}
	if rc.Facts != "(none)" && rc.Facts != "" {
		content += "## Project Facts\n" + rc.Facts + "\n\n"
	}

	outDir := filepath.Join(projectPath, ".agent-memory")
	os.MkdirAll(outDir, 0755)
	outFile := filepath.Join(outDir, "context.md")
	err = os.WriteFile(outFile, []byte(content), 0644)
	return outFile, err
}

